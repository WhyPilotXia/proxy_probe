    def test_partial_write_failure_preserves_legacy_json_and_yaml_and_removes_temporary(self):
        self.write_json(OLD_FILENAME)
        self.write_yaml(OLD_YAML_FILENAME)
        before = self.snapshot()
        original_temporary_file = tempfile.NamedTemporaryFile
        temporary_paths = []

        @contextmanager
        def failing_temporary_file(*args, **kwargs):
            with original_temporary_file(*args, **kwargs) as stream:
                temporary_paths.append(Path(stream.name))
                wrapped = mock.Mock(wraps=stream)
                wrapped.name = stream.name

                def partial_write(content):
                    stream.write(content[:len(content) // 2])
                    stream.flush()
                    raise OSError("disk full during write")

                wrapped.write.side_effect = partial_write
                yield wrapped

        with mock.patch.object(probe.tempfile, "NamedTemporaryFile", failing_temporary_file):
            with mock.patch.object(probe.os, "replace") as replace:
                with self.assertRaisesRegex(OSError, "disk full during write"):
                    probe.export_clash_yaml(self.records, self.directory, NOW)
        replace.assert_not_called()
        self.assertEqual(len(temporary_paths), 1)
        self.assertFalse(temporary_paths[0].exists())
        self.assertEqual(self.snapshot(), before)

