    def test_legacy_json_is_removed_only_after_complete_yaml_is_committed(self):
        old = self.write_json(OLD_FILENAME)
        old_yaml = self.write_yaml(OLD_YAML_FILENAME)
        original_replace = os.replace
        original_unlink = Path.unlink
        committed = []
        removed = []

        def check_unlink(path, *args, **kwargs):
            if path in (old, old_yaml):
                self.assertEqual(len(committed), 1, "新 YAML 提交成功后才可删除旧配置")
                self.assertTrue(committed[0].is_file())
                removed.append(path)
            return original_unlink(path, *args, **kwargs)

        def check_replace(source, destination):
            source, destination = Path(source), Path(destination)
            self.assertEqual(source.parent, destination.parent)
            self.assertEqual(source.parent, self.directory)
            self.assertNotEqual(source, destination)
            self.assertTrue(old.exists(), "提交成功前不得删除旧 JSON")
            self.assertTrue(old_yaml.exists(), "提交成功前不得删除旧 YAML")
            self.assertFalse(destination.exists())
            self.assertEqual(destination.suffix, ".yaml")
            self.assertTrue(source.read_text(encoding="utf-8").startswith(EXPORT_HEADER))
            self.assertEqual(
                yaml.safe_load(source.read_text(encoding="utf-8")),
                probe.build_clash_config(self.records),
            )
            original_replace(source, destination)
            committed.append(destination)

        with mock.patch.object(probe.os, "replace", side_effect=check_replace) as replace:
            with mock.patch.object(Path, "unlink", autospec=True, side_effect=check_unlink):
                path = probe.export_clash_yaml(self.records, self.directory, NOW)
        replace.assert_called_once()
        self.assertEqual(committed, [path])
        self.assertEqual(set(removed), {old, old_yaml})
        self.assertFalse(old.exists())
        self.assertFalse(old_yaml.exists())
        self.assertEqual(list(self.directory.iterdir()), [path])

